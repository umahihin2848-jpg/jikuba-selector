const fs=require('fs');
const path=require('path');
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const displayPath='waku-bc-converter/ability-field-structure-v1.js';
const opponentPath='waku-bc-converter/opponent-ranking-display-v1.js';
const validationPath='waku-bc-converter/validation/ability_gap_field_strength_shadow_v1.json';
const htmlPath='waku-bc-converter/v3.html';
const loaderPath='waku-bc-converter/v3-addons-loader-p.js';
const display=read(displayPath),opponent=read(opponentPath),html=read(htmlPath),loader=read(loaderPath),validation=JSON.parse(read(validationPath));
function ok(cond,msg){if(!cond)throw new Error(msg)}
new Function(display);
new Function(opponent);
ok(Buffer.byteLength(display)<20000,'Ability structure display unexpectedly large');
ok(Buffer.byteLength(opponent)<20000,'Opponent display unexpectedly large');
ok(!display.includes('setInterval('),'Ability structure display must not use setInterval');
ok(!display.includes('MutationObserver'),'Ability structure display must not use MutationObserver');
ok(!display.includes("addEventListener('ability-field-structure-ready'"),'Ability structure display must not listen to its own ready event');
ok(display.includes('productionImpact:false'),'Production isolation flag missing');
ok(display.includes('opponentVetoChanged:false'),'Opponent VETO isolation flag missing');
ok(display.includes('ticketLogicChanged:false'),'Ticket isolation flag missing');
ok(validation.status==='SHADOW_DISPLAY_ONLY','Validation status must remain Shadow display only');
ok(validation.production_impact===false,'Validation must not change Production');
ok(validation.source.races===700,'Expected frozen 2025-2026 race baseline of 700');
ok(validation.ability_gap_3_to_4.large_gap_races===140,'Large-gap validation race count drifted');
ok(validation.ability_gap_3_to_4.ability_rank4_top3.hits===42,'Large-gap rank4 top3 hits drifted');
ok(validation.ability_gap_3_to_4.ability_rank4_top3.rate===0.3,'Large-gap rank4 top3 rate drifted');
ok(validation.ability_gap_3_to_4.decision==='DO_NOT_AUTO_VETO_RANK4_FROM_GAP_ALONE','Gap-alone auto veto must remain disabled');
ok(opponent.includes('Math.min(n(r.abp3),n(r.m3p3))'),'Wide opponent ranking formula changed unexpectedly');
ok(opponent.includes('n(r.abp3)*n(r.m3p3)/win'),'Quinella opponent ranking formula changed unexpectedly');
ok(opponent.includes('ticketLogicChanged:false'),'Opponent display ticket isolation flag missing');
ok(html.includes('ability-field-structure-v1.js?v=20261101ability1'),'Ability structure script not wired into v3');
ok(html.includes('opponent-ranking-display-v1.js?v=20261101ability1'),'Opponent Ability value build not wired into v3');
ok(html.includes("window.RSA_BUILD='20261101ability1'"),'v3 build marker mismatch');
ok(loader.includes("const BUILD='20261101ability1'"),'addon loader build marker mismatch');
const totalN=Object.values(validation.same_grade_field_strength.baseline_2025_2026).reduce((s,x)=>s+x.n,0);
ok(totalN===700,'Same-grade field-strength baseline must sum to 700 races');
console.log(JSON.stringify({ok:true,displayBytes:Buffer.byteLength(display),opponentBytes:Buffer.byteLength(opponent),baselineRaces:validation.source.races,largeGapRaces:validation.ability_gap_3_to_4.large_gap_races,largeGapRank4Top3:validation.ability_gap_3_to_4.ability_rank4_top3.rate,productionImpact:false},null,2));

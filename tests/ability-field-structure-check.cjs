// Dedicated guard for display-only Ability structure changes.
const fs=require('fs');
const path=require('path');
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const displayPath='waku-bc-converter/ability-field-structure-v1.js';
const opponentPath='waku-bc-converter/opponent-ranking-display-v1.js';
const mobilePath='waku-bc-converter/mobile-product-ui-v1.js';
const validationPath='waku-bc-converter/validation/ability_gap_field_strength_shadow_v1.json';
const htmlPath='waku-bc-converter/v3.html';
const loaderPath='waku-bc-converter/v3-addons-loader-p.js';
const display=read(displayPath),opponent=read(opponentPath),mobile=read(mobilePath),html=read(htmlPath),loader=read(loaderPath),validation=JSON.parse(read(validationPath));
function ok(cond,msg){if(!cond)throw new Error(msg)}
new Function(display);
new Function(opponent);
new Function(mobile);
ok(Buffer.byteLength(display)<22000,'Ability structure display unexpectedly large');
ok(Buffer.byteLength(opponent)<20000,'Opponent display unexpectedly large');
ok(Buffer.byteLength(mobile)<30000,'Mobile product UI unexpectedly large');
ok(!display.includes('setInterval('),'Ability structure display must not use setInterval');
ok(!display.includes('MutationObserver'),'Ability structure display must not use MutationObserver');
ok(!display.includes("addEventListener('ability-field-structure-ready'"),'Ability structure display must not listen to its own ready event');
ok(display.includes("version:V,displayOnly:true,productionImpact:false")||display.includes('productionImpact:false'),'Production isolation flag missing');
ok(display.includes('opponentVetoChanged:false'),'Opponent VETO isolation flag missing');
ok(display.includes('ticketLogicChanged:false'),'Ticket isolation flag missing');
ok(display.includes('fullLadder:true'),'Full-rank ladder flag missing');
ok(display.includes("rows.slice(0,-1).map"),'All adjacent Ability ranks must be converted to gaps');
ok(display.includes('gapOrder'),'Ranked gap structure missing');
ok(display.includes('medianAdjacentGap'),'Whole-race adjacent-gap summary missing');
ok(display.includes('rows:rows.map'),'All Ability rows must be exposed, not only top-N');
ok(!display.includes('3位 → 4位の断層'),'3-to-4 must not remain the primary UI label');
ok(validation.status==='SHADOW_DISPLAY_ONLY','Validation status must remain Shadow display only');
ok(validation.production_impact===false,'Validation must not change Production');
ok(validation.source.races===700,'Expected frozen 2025-2026 race baseline of 700');
// Retain the old 3->4 diagnostic only as a safety reminder: gap alone must not auto-veto.
ok(validation.ability_gap_3_to_4.decision==='DO_NOT_AUTO_VETO_RANK4_FROM_GAP_ALONE','Gap-alone auto veto must remain disabled');
ok(opponent.includes('Math.min(n(r.abp3),n(r.m3p3))'),'Wide opponent ranking formula changed unexpectedly');
ok(opponent.includes('n(r.abp3)*n(r.m3p3)/win'),'Quinella opponent ranking formula changed unexpectedly');
ok(opponent.includes('ticketLogicChanged:false'),'Opponent display ticket isolation flag missing');
ok(opponent.includes('legacyDiagnostic:true'),'Old Ability x M3 opponent ranking must be diagnostic only');
ok(opponent.includes("productionPartnerSource:'market_top2_excluding_axis'"),'Official Production partner source must remain market top2');
ok(mobile.includes('abilityIndex:num(a.index)'),'Every-horse data must carry Ability index');
ok(mobile.includes('<span>Ability指数</span>'),'Expanded horse card must show Ability index');
ok(mobile.includes('abilityIndexVisible:true'),'Mobile UI state must declare Ability index visibility');
ok(mobile.includes('productionImpact:false'),'Mobile Ability index display must remain display-only');
ok(!mobile.includes('setInterval('),'Mobile Ability index display must not add polling loops');
ok(html.includes('ability-field-structure-v1.js?v=20261101ability2'),'Ability structure script not wired into v3');
ok(html.includes('opponent-ranking-display-v1.js?v=20261102review1'),'Reviewed legacy opponent diagnostic not wired into v3');
ok(html.includes('mobile-product-ui-v1.js?v=20261101ability3'),'Mobile Ability index cache key not wired into v3');
ok(html.includes("window.RSA_BUILD='20261101ability2'"),'v3 build marker mismatch');
ok(loader.includes("const BUILD='20261101ability2'"),'addon loader build marker mismatch');
const totalN=Object.values(validation.same_grade_field_strength.baseline_2025_2026).reduce((s,x)=>s+x.n,0);
ok(totalN===700,'Same-grade field-strength baseline must sum to 700 races');
console.log(JSON.stringify({ok:true,displayBytes:Buffer.byteLength(display),opponentBytes:Buffer.byteLength(opponent),mobileBytes:Buffer.byteLength(mobile),baselineRaces:validation.source.races,fullLadder:true,abilityIndexVisible:true,legacyDiagnostic:true,autoVeto:false,productionImpact:false},null,2));

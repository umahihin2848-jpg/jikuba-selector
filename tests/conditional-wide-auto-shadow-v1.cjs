/* Pure, offline, non-production validation of automatic conditional Wide shadow. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const script=fs.readFileSync('waku-bc-converter/conditional-wide-auto-shadow-v1.js','utf8');
const env={window:{}};vm.runInNewContext(script,env,{timeout:4000});
const core=env.window.RSAConditionalWideAutoCoreV1;
assert(core?.compute&&core?.price);
const N=12,p3=3/N,pair=6/(N*(N-1)),ability={ready:true,activeModel:'v1',
 rows:Array.from({length:N},(_,i)=>({no:String(i+1),name:'Horse'+(i+1)}))};
const horses=ability.rows.map(r=>({...r,pTop3:p3})),pairMap={};
for(let i=0;i<N;i++)for(let j=i+1;j<N;j++)pairMap[(i+1)+'-'+(j+1)]={pWide:pair};
const shadow={ready:true,marketIndependent:true,field:N,horses,pairMap,
 coherence:{converged:true,sumWide:3,maxMarginalError:1e-9,maxDegreeError:1e-9}};
const req={axisNo:'1',partnerNos:['2','3','4'],ability,shadow};
const close=(a,b)=>assert(Math.abs(a-b)<1e-9,'expected '+b+', got '+a);
const res=core.compute(req);
assert.equal(res.ready,true);
assert.equal(res.marketAvailable,false);
assert.equal(res.partners.length,3);
close(res.axisTop3,p3);
close(res.partners[0].joint,pair);
close(res.partners[0].conditional,pair/p3);
close(core.price(pair,10).researchRoi,pair*10);
assert.equal(core.price(pair,'').ready,false);
assert.equal(core.price(pair,0).ready,false);
assert.equal(core.price(pair,3).breakEvenOdds,1/pair);
assert.equal(core.compute({...req,partnerNos:['1','2','3']}).ready,false);
assert.equal(core.compute({...req,partnerNos:['2','2','4']}).ready,false);
assert.equal(core.compute({...req,ability:{...ability,rows:ability.rows.map((x,i)=>i===0?{...x,name:'OTHER'}:x)}}).ready,false);
assert.equal(core.compute({...req,shadow:{...shadow,coherence:{...shadow.coherence,sumWide:2.8}}}).ready,false);
assert.equal(core.compute({...req,shadow:{...shadow,coherence:{...shadow.coherence,converged:false}}}).ready,false);
assert.equal(core.compute({...req,shadow:{...shadow,marketIndependent:false}}).ready,false);
const map={};
for(let i=0;i<N;i++)for(let j=i+1;j<N;j++)map[(i+1)+'-'+(j+1)]={a:ability.rows[i],b:ability.rows[j],wide:pair};
const mr=core.compute({...req,market:{ready:true,marketDerived:true,axisNo:'1',field:N,pairMap:map}});
assert.equal(mr.ready,true);
assert.equal(mr.marketAvailable,true);
close(mr.marketAxisTop3,p3);
close(mr.partners[0].market.joint,pair);
close(mr.partners[0].market.conditional,pair/p3);
assert.equal(core.compute({...req,market:{ready:true,marketDerived:true,axisNo:'8',field:N,pairMap:map}}).marketAvailable,false);
const gc=core.compute({...req,ability:{...ability,activeModel:'C'}});
assert.equal(gc.ready,true);
assert.equal(gc.abilityCUncalibrated,true);
const html=fs.readFileSync('waku-bc-converter/v3.html','utf8');
assert(html.includes('conditional-wide-auto-shadow-v1.js?v=20261125auto1'));
assert(html.includes('conditional-wide-auto-shadow-v1.css?v=20261125auto1'));
const forecast=fs.readFileSync('waku-bc-converter/mobile-forecast-workflow-v1.js','utf8');
assert(forecast.includes('conditionalWideAutoResearch:root.RSAConditionalWideAutoV1'));
assert(!script.includes('ProductionDecisionPipelineV1State='));
assert(!script.includes('M3PureAbilityState='));
assert(!script.includes('betEligible:true'));
console.log('conditional-wide-auto-shadow PASS: probability identity, coherence, market comparison, stale guard, grade-C label, snapshot & non-production');

"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const source=fs.readFileSync(path.join(__dirname,"../waku-bc-converter/mobile-forecast-workflow-v1.js"),"utf8");
const sandbox={window:{}};
vm.runInNewContext(source,sandbox,{filename:"mobile-forecast-workflow-v1.js"});
const core=sandbox.window.RSAForecastWorkflowCoreV1;
assert.ok(core,"pure runtime API must be available without DOM");
const left=["東京","新潟","中京"];
const right=["札幌","函館","福島","中山","京都","阪神","小倉"];
for(const v of left)assert.equal(core.turnForVenue(v,"芝",1600),"left");
for(const v of right)assert.equal(core.turnForVenue(v,"芝",1600),"right");
assert.equal(core.turnForVenue("新潟","芝",1000),"straight");
assert.equal(core.turnForVenue("新潟","ダ",1200),"left");
assert.equal(core.turnForVenue("未知の場","芝",1600),null);
for(let n=12;n<=18;n++){
 const roster=Array.from({length:n},(_,i)=>({no:String(i+1),name:"馬"+(i+1)}));
 const byNo=Object.fromEntries(roster.map((h,i)=>[h.no,{expectedRank:i+1,laneIdx:i%4,validated:true}]));
 const m={roster,byNo,axis:"7",partners:["3","11","14"]};
 const r=core.formationSVG(m,"right"),l=core.formationSVG(m,"left");
 assert.equal(r.known.length,n);assert.equal(l.known.length,n);
 assert.equal(r.unknown.length,0);
 assert.equal(r.known.filter(x=>x.no==="7").length,1);
 assert.equal(r.svg.match(/<circle cx=/g).length,n);
 assert.equal(l.svg.match(/<circle cx=/g).length,n);
 assert.ok(!r.svg.includes("marker-end"));
 assert.ok(!l.svg.includes("marker-end"));
 assert.ok(!r.svg.includes("→"));
 const c=s=>Number(s.match(/<title>7番 [^<]+<\/title><circle cx="([\d.]+)"/)[1]);
 assert.ok(Math.abs((c(r.svg)+c(l.svg))-360)<0.03,"mirror x coordinate must sum to view width");
 const slots=core.positionSlots(m);
 assert.equal(slots.known.length,n);
 assert.ok(slots.known.every(x=>Number.isFinite(x.x)&&x.x>=30&&x.x<=330));
 delete m.byNo[String(n)];
 assert.equal(core.positionSlots(m).unknown.length,1,"unknown placements must not be invented");
}
assert.match(core.riskFor({expectedRank:15,laneIdx:3,validated:true},16,"高"),/後方想定/);
assert.match(core.riskFor({expectedRank:1,laneIdx:0,validated:true},16,"高"),/先行争い/);
assert.match(core.riskFor(null,16,""),/未取得/);
console.log("forecast workflow: turn, all 12-18 horses, mirroring, risk, uncertainty, no arrows: PASS");

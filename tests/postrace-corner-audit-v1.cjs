"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const core=fs.readFileSync(path.join(__dirname,"../waku-bc-converter/postrace-corner-core-v1.js"),"utf8");
const sandbox={window:{}};
vm.runInNewContext(core,sandbox,{filename:"postrace-corner-core-v1.js"});
const A=sandbox.window.RSAPostraceCornerCoreV1;
assert.ok(A,"pure parser and visualizer must be exposed without DOM");
for(let n=12;n<=18;n++){
 const roster=Array.from({length:n},(_,i)=>({no:String(i+1),name:"Horse "+(i+1)}));
 const actual=roster.map((h,i)=>[h.no,i+1,i+1,i+1].join(" ")).join("\n");
 const p=A.parse(actual,roster,"1");
 assert.equal(p.ok,true,n+" horse valid result");
 assert.equal(Object.keys(p.values).length,n);
 assert.equal(p.values["1"].initial,1);
 const race={date:"2026-11-20",venue:"東京"};
 const formation=roster.map((h,i)=>({no:h.no,name:h.name,expectedRank:i+1,laneIdx:i%4}));
 const snap={locked:true,race,formation};
 const context={key:"race",race,roster,frozen:snap,axis:"7",partners:["3","11","14"]};
 const result={version:"postrace-corner-ui-v1-20261124",raceKey:"race",actual:p.values,firstCorner:"1"};
 assert.equal(A.validSaved(result,context),true);
 const metrics=A.compare(context,result);
 assert.equal(metrics.frozen,true);
 assert.equal(metrics.count,n);
 assert.equal(metrics.mae,0);
 assert.equal(metrics.bias,0);
 const without=A.compare({...context,frozen:null},result);
 assert.equal(without.count,0,"no retrospective pseudo-forecast");
 assert.equal(without.frozen,false);
 const wrong={...context,roster:roster.map((h,i)=>i===0?{...h,name:"different horse"}:h)};
 assert.equal(A.frozen(wrong),null,"reject identity mismatch");
 for(const stage of ["initial","c3","c4"]){
  const r=A.actualMap(context,result,stage,"right"),l=A.actualMap(context,result,stage,"left");
  assert.equal(r.known.length,n);assert.equal(r.unknown.length,0);
  assert.equal((r.svg.match(/<circle cx=/g)||[]).length,n);
  assert.equal((l.svg.match(/<circle cx=/g)||[]).length,n);
  assert.ok(!r.svg.includes("marker-end")&&!l.svg.includes("marker-end"));
  const cx=s=>Number(s.match(/<title>7番 [^<]+<\/title><circle cx="([\d.]+)"/)[1]);
  assert.ok(Math.abs(cx(r.svg)+cx(l.svg)-360)<0.03,"mirror and readable horse number");
 }
 const tied=roster.map((h,i)=>[h.no,1,1,1].join(" ")).join("\n");
 const q=A.parse(tied,roster,"1");assert.equal(q.ok,true,"recorded shared ranks allowed");
 const d=A.actualMap(context,{actual:q.values,firstCorner:"1"},"initial","right");
 assert.equal((d.svg.match(/<circle cx=/g)||[]).length,n,"no horse omitted when positions tie");
 const height=Number(d.svg.match(/viewBox="0 0 360 ([\d.]+)"/)[1]);
 assert.ok(height>=n*38,"all shared-rank horses spaced vertically instead of overwritten");
 const tooHigh=roster.map((h,i)=>[h.no,i===0?n+1:i+1,i+1,i+1].join(" ")).join("\n");
 assert.equal(A.parse(tooHigh,roster,"1").ok,false);
 assert.equal(A.parse(actual.split("\n").slice(0,-1).join("\n"),roster,"1").ok,false);
 assert.equal(A.parse([actual.split("\n")[0],...actual.split("\n").slice(0,-1)].join("\n"),roster,"1").ok,false);
 const rows3=roster.map((h,i)=>[h.no,i+1,i+1,i+1].join(" ")).join("\n");
 assert.equal(A.parse(rows3,roster,"3").ok,true);
 const bad3=rows3.replace("1 1 1 1","1 1 2 1");
 assert.equal(A.parse(bad3,roster,"3").ok,false,"first recorded C3 cannot contradict C3");
 const rows4=roster.map((h,i)=>[h.no,i+1,"-",i+1].join(" ")).join("\n");
 assert.equal(A.parse(rows4,roster,"4").ok,true);
 assert.equal(A.parse(rows3,roster,"4").ok,false,"never fabricate C3 before first recorded C4");
 const missing=roster.map((h,i)=>[h.no,i+1,"-",i+1].join(" ")).join("\n");
 const missingMap=A.actualMap(context,{actual:A.parse(missing,roster,"1").values,firstCorner:"1"},"c3","left");
 assert.equal(missingMap.known.length,0);
 assert.equal(missingMap.unknown.length,n);
}
console.log("postrace corner audit: 12–18 horses, ties, missing corners, C3/C4 consistency, frozen-only scoring, mirroring: PASS");
